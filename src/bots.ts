export const BOT_USER_AGENT = new RegExp(BOT_PATTERNS.join("|"), "i");

/** Detects crawlers, link previewers, headless browsers, monitors and HTTP clients. */
export function isBot(userAgent: string | null | undefined): boolean {
  if (typeof userAgent !== "string") return false;
  const ua = userAgent.trim();
  return ua.length > 0 && BOT_USER_AGENT.test(ua);
}
